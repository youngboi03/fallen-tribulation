"""Merge tools/loc/*.txt (vi|en|zh) into Assets/Resources/Loc/strings.txt (tab-separated)
and report source strings that would still show Vietnamese after translation.
Usage: python -I tools/loc/build_loc.py [--check]"""
import os, re, sys, glob
sys.stdout.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(PROJ, 'Assets', 'Resources', 'Loc', 'strings.txt')
VI = re.compile(r'[À-ÖØ-öø-ỹĐđ]')   # Latin letters with diacritics, not × ÷

rows, seen = [], {}
for f in sorted(glob.glob(os.path.join(HERE, '*.txt'))):
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'): continue
        p = line.split('|')
        if len(p) != 3 or not all(x.strip() for x in p):
            print(f'BAD {os.path.basename(f)}:{n}: {line}'); continue
        if p[0] in seen and seen[p[0]] != (p[1], p[2]):
            print(f'DUP {os.path.basename(f)}:{n}: {p[0]}')
        seen[p[0]] = (p[1], p[2])
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8', newline='\n') as o:
    o.write('# generated by tools/loc/build_loc.py — edit tools/loc/*.txt instead\n')
    for k, (en, zh) in seen.items(): o.write(f'{k}\t{en}\t{zh}\n')
print(f'{len(seen)} phrases -> {OUT}')

# ---- simulate Loc.Tr (same algorithm as Core/Loc.cs) on every source literal
def build(lang):
    t = {}
    def add(k, v):
        t.setdefault(k[0], []).append((k, v))
    for k, v in seen.items():
        val = v[lang - 1]
        add(k, val)
        if k.upper() != k: add(k.upper(), val if lang == 2 else val.upper())
    for l in t.values(): l.sort(key=lambda kv: -len(kv[0]))
    return t
def wc(c): return c.isalnum()
def tr(s, t):
    out, i, n = [], 0, len(s)
    while i < n:
        c = s[i]
        if c == '<':
            j = s.find('>', i)
            if j > i: out.append(s[i:j+1]); i = j + 1; continue
        done = False
        if (i == 0 or not wc(s[i-1])) and c in t:
            for k, v in t[c]:
                L = len(k)
                if s.startswith(k, i) and not (i + L < n and wc(s[i+L]) and wc(k[-1])):
                    out.append(v); i += L; done = True; break
        if not done: out.append(c); i += 1
    return ''.join(out)

if '--check' in sys.argv:
    ten, tzh = build(1), build(2)
    lit = re.compile(r'(?<![\w@$])"((?:[^"\\\n]|\\.)*)"')
    miss = {}
    for f in glob.glob(os.path.join(PROJ, 'Assets', 'Scripts', '**', '*.cs'), recursive=True):
        if os.sep + 'Auto' + os.sep in f or os.sep + 'Editor' + os.sep in f: continue
        for line in open(f, encoding='utf-8'):
            st = line.strip()
            if st.startswith('//') or 'Debug.Log' in st: continue
            for m in lit.finditer(line):
                s = m.group(1).replace('\\n', '\n').replace('\\"', '"')
                if not VI.search(s): continue
                e = re.sub(r'<[^>]*>', '', tr(s, ten))
                if VI.search(e): miss[s] = (os.path.basename(f), e)
    for s, (f, e) in sorted(miss.items(), key=lambda kv: kv[1][0]):
        print(f'[{f}] {s!r}\n      -> {e!r}')
    print(f'{len(miss)} literals still contain Vietnamese in EN')
    if '--samples' in sys.argv:
        import random; random.seed(3)
        allv = []
        for f in glob.glob(os.path.join(PROJ, 'Assets', 'Scripts', '**', '*.cs'), recursive=True):
            for line in open(f, encoding='utf-8'):
                for m in lit.finditer(line):
                    s = m.group(1)
                    if VI.search(s) and len(s) > 12: allv.append(s)
        for s in random.sample(allv, 30):
            print('VI', s); print('EN', tr(s, ten)); print('ZH', tr(s, tzh)); print()
